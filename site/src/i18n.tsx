export type Dict = (typeof dict)['ar']

type Ctx = {
  lang: Lang
  t: Dict
  dir: 'rtl' | 'ltr'
  toggle: () => void
  l: (v: L10n) => string
  egp: (n: number) => string
  num: (n: number) => string
}

const I18nCtx = createContext<Ctx | null>(null)

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(() => {
    try {
      const saved = localStorage.getItem('rz-lang')
      if (saved === 'ar' || saved === 'en') return saved
    } catch { /* storage unavailable */ }
    return 'ar'
  })

  useEffect(() => {
    const el = document.documentElement
    el.lang = lang
    el.dir = lang === 'ar' ? 'rtl' : 'ltr'
    try { localStorage.setItem('rz-lang', lang) } catch { /* ignore */ }
  }, [lang])

  const toggle = useCallback(() => setLang((v) => (v === 'ar' ? 'en' : 'ar')), [])

  const value = useMemo<Ctx>(() => {
    const locale = lang === 'ar' ? 'ar-EG' : 'en-US'
    const nf = new Intl.NumberFormat(locale)
    return {
      lang,
      t: dict[lang] as Dict,
      dir: lang === 'ar' ? 'rtl' : 'ltr',
      toggle,
      l: (v) => v[lang],
      num: (n) => nf.format(n),
      egp: (n) => `${nf.format(n)} ${dict[lang].common.egp}`,
    }
  }, [lang, toggle])

  return <I18nCtx.Provider value={value}>{children}</I18nCtx.Provider>
}

export function useI18n() {
  const ctx = useContext(I18nCtx)
  if (!ctx) throw new Error('useI18n must be used inside I18nProvider')
  return ctx
}
